SYSTEM='''You are a model-research coding agent. Use only public development material.
Respond with one JSON object per turn. Tools have {"tool":name,"arguments":{...}}.
File tools: list {}, read {path}, write {path,content}, check {path}. Paths are workspace-relative.
Research tools: inspect {}, development_summary {}, register_hypothesis {claim,predicted_direction,alternative,would_weaken_claim},
baseline {case_id,hypothesis_id}, probe {case_id,patch,hypothesis_id}, full_development {patch,hypothesis_id}, export {patch,hypothesis_id}.
Research calls require a controller-registered hypothesis ID. Every experiment starts pristine. Use available development cases, not private inputs.
Finish {"done":true}. Write submission.json using the exact schema in TASK.md; code must actually run and reproduce its patch with research_tools.export_head or explicitly abstain.
Write claims.json predictions for ALL common challenges; direction is decrease, none, or increase, optionally magnitude/confidence. Predictions describe mean intervention-minus-pristine fixed-token log probability.
No protected results are available. Previously exposed material is development, not fresh confirmation. Do not claim a mechanism from a norm or one successful intervention.
'''


def invoke(request, directory, timeout=120):
    """Trusted writer supervisor without the coding sandbox's 2 MB checkpoint file cap."""
    directory=Path(directory);directory.mkdir(parents=True,exist_ok=True)
    save(directory/'request.json',request);start=time.monotonic()
    env={k:v for k,v in os.environ.items() if not k.endswith(('API_KEY','TOKEN'))}
    with (directory/'process.log').open('w') as log:
        proc=subprocess.Popen([str(ROOT/'.audio-venv/bin/python'),'-m','research_eval.tools_worker',str(directory/'request.json'),str(directory/'result.json')],
                             cwd=ROOT,env=env,stdout=log,stderr=log,start_new_session=True)
        try:code=proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            os.killpg(proc.pid,signal.SIGKILL);proc.wait();code=124
        finally:
            try:os.killpg(proc.pid,signal.SIGKILL)
            except ProcessLookupError:pass
    if code or not (directory/'result.json').exists():
        raise RuntimeError('Audio subprocess '+('timed out' if code==124 else 'failed; see '+str(directory/'process.log')))
    result=read(directory/'result.json')
    if result['status']!='ok':raise ValueError(result.get('error','Audio operation failed'))
    result['supervised_seconds']=time.monotonic()-start;return result


def scaffold(research, episode_id, policy_version):
    task=research.task();work=research.root/'episodes'/episode_id/'workspace';work.mkdir(parents=True)
    save(work/'TASK.json',task['public'])
    schema=dict(episode_id=episode_id,task_version=task['version'],agent_policy_version=policy_version,
                parent_checkpoint_sha256=OFFICIAL_SMALL_SHA256,code_artifact='replay.py',patch_manifest=None,
                checkpoint_artifact=None,claims_artifact='claims.json',experiment_log='experiments.jsonl',
                decision='abstain',reported_limitations=[],reproduction=dict(entrypoint='replay.py',dependencies=['numpy','torch','openai-whisper==20250625']))
    text='''# Public research task
Investigate multilingual Whisper-small unsupported non-speech continuation. Existing development evidence and baseline results are exposed. Use the trusted research tools for model experiments. All genuine speech must be retained in full evaluation. Predictions must cover TASK.json common_challenge_grid. See TASK.json for fixed configuration, budgets and gate.

Submission schema (fill actual decision/artifact paths):
'''+json.dumps(schema,indent=2)+'''

Patch format: {"kind":"decoder_self_attention_head_scale","layer":4,"head":4,"scale":0.5,"parent_checkpoint_sha256":"'''+OFFICIAL_SMALL_SHA256+'''"}.
Only one head edit, allowed scales in TASK.json. The checkpoint artifact is candidate.npz, generated by research_tools.export_head(layer,head,scale,'candidate.npz'). This public dependency reads only the official parent. The independent evaluator reconstructs the full checkpoint and checks unrelated tensors. Do not submit a pickle or .pt.

replay.py must regenerate the declared candidate NPZ for patch submissions, and write replay_result.json containing {"decision": "abstain" or "submit_patch", "patch": null or the exact patch object, "checks":[{"name":"an actual executed software check","passed":true}]}. For abstention it must execute the investigation's software checks and produce evidence; it must not just print a narrative. Include dependencies, all experiment records (copy controller_experiments.jsonl plus your code experiments), errors and limitations. Write frozen common-grid predictions in claims.json as {"predictions":{"challenge_id":{"direction":"none"}}}. Agent-authored tests support evidence; trusted gates determine acceptance.
'''
    (work/'TASK.md').write_text(text);(work/'TASK.md').chmod(0o444)
    (work/'research_tools.py').write_text(helper_source(ROOT/'audio_models/small.pt'))
    save(work/'development.json',rows(ROOT/'whisper_audio_dev/manifest.jsonl'))
    save(work/'recorded_baseline.json',read(ROOT/'audio_runs/mechanistic_v1/baseline_metrics.json'))
    save(work/'available_probes.json',[dict(case_id=read(p)['case_id'],cohort=read(p)['cohort'],prefix_token_ids=read(p)['prefix_token_ids'],
                                         target_position=read(p)['target_position'],target_token_id=read(p)['target_token_id'])
                                        for p in sorted((ROOT/'audio_runs/mechanistic_v1/cases').glob('*.json'))])
    return work


def run_episode(research, condition, attempt):
    comparison=research.state.read('comparison');task=research.task()
    if not comparison or condition not in comparison['policies'] or attempt not in (1,2):raise ValueError('Choose a frozen scheduled attempt')
    if research.state.read('comparison_seal'):raise ValueError('Sealed comparisons cannot run new attempts')
    if any(e.get('condition')==condition and e.get('attempt')==attempt for e in research.episodes()):raise ValueError('Attempt already recorded; start a new comparison to retry')
    model=Model()
    if model.identity()!=comparison['model']:raise ValueError('Model identity changed')
    episode_id=uuid.uuid4().hex;directory=research.root/'episodes'/episode_id;policy_version=comparison['policies'][condition]
    work=scaffold(research,episode_id,policy_version);journal=State(directory/'journal');files=Files(work,Sandbox('local-unenforced'))
    episode=dict(id=episode_id,kind='live_agent',condition=condition,attempt=attempt,comparison_member=True,
                 policy_version=policy_version,task_version=task['version'],seed=1728+attempt,model=model.identity(),
                 status='running',started=now(),isolation=ISOLATION,budgets=BUDGET,source_snapshot_hash=comparison['source_snapshot_hash'])
    policy=research.policies.get(policy_version)
    messages=[dict(role='system',content=SYSTEM+'\nImmutable procedure:\n'+canonical(policy['content'])),
              dict(role='user',content=(work/'TASK.md').read_text())]
    episode['prompt_hash']=digest(messages);save(research.root/'episodes'/(episode_id+'.json'),episode)
    journal.emit('episode_started',episode_id=episode_id,prompt_hash=episode['prompt_hash'])
    start=time.monotonic();counts=dict(model_calls=0,tool_calls=0,tokens=0,prompt_tokens=0,completion_tokens=0,
                                     whisper_evaluations=0,whisper_reserved=0,usage_reported=True)
    status='budget_exhausted';error=None;hypotheses={};experiments=[]
    while counts['model_calls']<BUDGET['model_calls'] and time.monotonic()-start<BUDGET['seconds']:
        reserve=len(canonical(messages).encode())+BUDGET['output_tokens']+128
        if counts['tokens']+reserve>BUDGET['tokens']:break
        counts['model_calls']+=1
        try:raw,usage=model.complete(messages,BUDGET['output_tokens'],min(60,BUDGET['seconds']-(time.monotonic()-start)))
        except InfrastructureError as exc:
            status='infrastructure_failure';error=str(exc);counts['usage_reported']=False
            journal.emit('model_failure',error=error);break
        used=usage.get('total_tokens',reserve);counts['tokens']+=used
        for name in ('prompt_tokens','completion_tokens'):counts[name]+=usage.get(name,0)
        counts['usage_reported'] &= 'total_tokens' in usage
        journal.emit('model_call',usage=usage,accounted_tokens=used);messages.append(dict(role='assistant',content=raw))
        experiment_id=None
        try:
            action=json.loads(raw)
            if action.get('done') is True:status='submitted' if (work/'submission.json').exists() else 'missing_submission';break
            if counts['tool_calls']>=BUDGET['tool_calls']:break
            counts['tool_calls']+=1;name=action['tool'];args=action.get('arguments',{})
            if name in ('list','read','write','check'):
                if name=='write' and args.get('path') in ('TASK.json','research_tools.py','development.json','recorded_baseline.json','available_probes.json'):raise ValueError('Public fixtures are immutable')
                # Python execution is logical-only on this host. No private data path is supplied.
                if name=='check':
                    target=files.path(args['path']);reply=files.sandbox.run([str(ROOT/'.audio-venv/bin/python'),str(target)],work,timeout=min(30,BUDGET['seconds']-(time.monotonic()-start)))
                else:reply=files.call(name,args)
            elif name=='inspect':
                if args:raise ValueError('Unexpected inspection arguments')
                reply=dict(layers=12,heads=12,state=768,head_dim=64,allowed_scales=task['public']['allowed_interventions']['scales'])
            elif name=='development_summary':
                if args:raise ValueError('No selectors accepted')
                reply=dict(recorded_baseline=read(work/'recorded_baseline.json'),probes=read(work/'available_probes.json'),fresh=False)
            elif name=='register_hypothesis':
                keys={'claim','predicted_direction','alternative','would_weaken_claim'}
                if set(args)!=keys or not all(isinstance(v,str) and 1<=len(v)<=3000 for v in args.values()):raise ValueError('Invalid hypothesis')
                hid=uuid.uuid4().hex;hypotheses[hid]=args;journal.emit('hypothesis_registered',hypothesis_id=hid,record=args)
                reply=dict(hypothesis_id=hid,registered_before_future_experiments=True)
            elif name in ('baseline','probe','full_development','export'):
                fields={'hypothesis_id'}|({'case_id'} if name in ('baseline','probe') else set())|({'patch'} if name!='baseline' else set())
                if set(args)!=fields or args['hypothesis_id'] not in hypotheses:raise ValueError('Register a hypothesis and use exact declared tool fields')
                if 'patch' in args:validate_patch(args['patch'])
                if 'case_id' in args and args['case_id'] not in {x['id'] for x in read(work/'development.json')}:raise ValueError('Only public development IDs allowed')
                if name=='probe' and args['case_id'] not in {x['case_id'] for x in read(work/'available_probes.json')}:raise ValueError('No aligned probe for this case')
                cost=29 if name=='full_development' else 2 if name=='probe' else 1 if name=='baseline' else 0
                estimated=100 if name=='full_development' else 25
                if counts['whisper_reserved']+cost>BUDGET['whisper_evaluations'] or time.monotonic()-start+estimated>BUDGET['seconds']:raise ValueError('Comparison would exceed remaining budget')
                counts['whisper_reserved']+=cost;experiment_id=uuid.uuid4().hex
                journal.emit('experiment_started',experiment_id=experiment_id,hypothesis_id=args['hypothesis_id'],operation=name,arguments=args,reserved_model_evaluations=cost)
                target=directory/'tools'/experiment_id
                request=dict(operation=name,directory=str(target/'artifacts'),**{k:v for k,v in args.items() if k!='hypothesis_id'})
                if name=='export':
                    request['operation']='construct';request['fixtures']=[]
                result=invoke(request,target,timeout=estimated)
                counts['whisper_evaluations']+=cost
                experiment=dict(id=experiment_id,hypothesis_id=args['hypothesis_id'],operation=name,arguments=args,result_sha256=sha(target/'result.json'),status='complete')
                experiments.append(experiment);journal.emit('experiment_complete',**experiment)
                with (work/'controller_experiments.jsonl').open('a') as stream:stream.write(canonical(experiment)+'\n')
                reply=result
                if name=='export':
                    import shutil
                    shutil.copy2(target/'artifacts/candidate.npz',work/'candidate.npz');reply=dict(exported='candidate.npz',sha256=sha(work/'candidate.npz'))
            else:raise ValueError('Tool not allowlisted')
            journal.emit('tool_result',tool=name,arguments=args,result=str(reply)[:3000])
        except (ValueError,KeyError,TypeError,OSError,RuntimeError) as exc:
            reply={'tool_error':str(exc)[:1000]};journal.emit('tool_failure',error=reply)
            if experiment_id:
                failed=dict(id=experiment_id,hypothesis_id=args['hypothesis_id'],operation=name,arguments=args,status='failed',error=reply['tool_error'])
                journal.emit('experiment_failed',**failed)
                with (work/'controller_experiments.jsonl').open('a') as stream:stream.write(canonical(failed)+'\n')
        messages.append(dict(role='user',content=canonical(reply)[:30000]))
    elapsed=time.monotonic()-start
    episode.update(status=status,error=error,finished=now(),elapsed_seconds=elapsed,usage=counts,
                   within_budget=elapsed<=BUDGET['seconds']+.5 and counts['tokens']<=BUDGET['tokens'] and counts['whisper_reserved']<=BUDGET['whisper_evaluations'])
    save(directory/'trajectory.json',messages);save(research.root/'episodes'/(episode_id+'.json'),episode)
    journal.emit('episode_finished',status=status,usage=counts)
    if status=='submitted':
        try:research.freeze_submission(episode_id)
        except (ValueError,OSError,KeyError) as exc:
            episode.update(status='invalid_submission',error=str(exc));save(research.root/'episodes'/(episode_id+'.json'),episode)
    return episode
